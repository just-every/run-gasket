  assert.equal((await h.api(record,cookie.lead)).bom.revision,1)
  await open(`/app/assets/${asset}`,'retained-lifecycle-and-bom')

  await open('/app/templates','work-field-definition')
  await save('workfield.save',{'Field':'Guard inspection reference','Kind':'text'},'work-fields')
  const workField=(await h.api('work-fields',cookie.lead)).fields.find(row=>row.label==='Guard inspection reference')
  assert.equal(workField.kind,'text')
  await form('workstatus.save').getByLabel('Leads',{exact:true}).check()
  await save('workstatus.save',{'Status':'Waiting for guard access'},'work-fields')
