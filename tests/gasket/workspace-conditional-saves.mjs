  await save('code.retire',{'Code':'guard_resonance','Reason':'Use the revised mechanical fault classification'},'codes',codeForm('code.retire'))
  assert.equal((await h.api('codes',cookie.lead)).find(row=>row.key==='guard_resonance').retired,true)
  await open('/app/codes','retired-failure-code')
  await open('/app/availability','production-hours-entry')
  await form('production.hours.add').getByLabel('Monday',{exact:true}).check()
  await save('production.hours.add',{'Starts':'07:00','Ends':'15:00'},'availability')
  const hours=(await h.api('availability',cookie.lead)).production.hours.find(row=>row.starts==='07:00'&&row.ends==='15:00')
  assert.equal(hours.weekday,1)
  await save('production.hours.remove',{'Remove a window':hours.id},'availability')
  assert.equal((await h.api('availability',cookie.lead)).production.hours.some(row=>row.id===hours.id),false)

  await open('/app/notices','chase-policy-entry')
  await save('chase.rule',{'Remind before due (days)':'2','Response expected within (days)':'2','Escalate to leads after (days overdue)':'3','Escalate to supervisors after (days overdue)':'5'},'chase-rule')
  assert.equal((await h.api('chase-rule',cookie.lead)).remind_before_days,2)
