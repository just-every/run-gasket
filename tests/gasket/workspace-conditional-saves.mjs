// Additional record states share the workspace journey's real save boundaries.
import assert from 'node:assert/strict'
import { png } from './fixtures.mjs'

export async function conditionalSaves({h,cookie,page,use,open,submit,proof,day,technician,longName,part}) {
  const asset=(await h.api('asset.create',cookie.lead,{tag:'ACCESS-STATES',name:longName,location:'West maintenance workshop'})).id
  const job=(await h.api('workorder.create',cookie.lead,{asset,title:'Inspect guard with the maintenance crew',due:day,assignee:technician})).id
  const work=`work/${job}`, record=`assets/${asset}`
  const windowDay=new Date(Date.parse(day+'T12:00Z')+2*86_400_000).toISOString().slice(0,10)
  const form=action=>page.locator(`form[action="/app/do/${action}"]`)
  async function save(action,fields,view,which) {
    const target=which || form(action)
    for (const detail of await target.locator('xpath=ancestor::details').all()) {
      if (!await detail.evaluate(el=>el.open)) await detail.locator(':scope > summary').click()
    }
    for (const [label,value] of Object.entries(fields)) {
      const control=target.getByLabel(label,{exact:true})
      if (typeof value==='object') await control.setInputFiles(value)
      else if (await control.evaluate(el=>el.tagName)==='SELECT') await control.selectOption(value)
      else await control.fill(value)
    }
    await submit(target,/Saved/,view)
  }
  await use('owner')
  await open('/app/settings/resources','resource-availability')
  await save('planning.window',{'Person':technician,'Window':'available','Starts':`${windowDay}T06:00`,'Ends':`${windowDay}T18:00`,'Reason':'Explicit workshop shift'},'planning')
  assert.ok((await h.api('planning',cookie.owner)).windows.some(row=>row.member_id===technician&&row.reason==='Explicit workshop shift'))
  const window=(await h.api('planning',cookie.owner)).windows.find(row=>row.reason==='Explicit workshop shift')
  const remove=form('planning.window.remove').filter({has:page.locator(`[name=id][value="${window.id}"]`)})
  await save('planning.window.remove',{'Removal reason':'Replaced by the confirmed production shift'},'planning',remove)
  assert.equal((await h.api('planning',cookie.owner)).windows.some(row=>row.reason==='Explicit workshop shift'),false)
  await open('/app/settings/resources','qualification-entry')
  await save('planning.qualification',{'Person':technician,'Qualification':'Guard inspection reference','Valid through':'2099-12-31','Evidence reference':'Owner-entered workshop reference'},'planning')
  assert.equal((await h.api('planning',cookie.owner)).qualifications.find(row=>row.name==='Guard inspection reference').reference,'Owner-entered workshop reference')
  await save('planning.requirements',{'Work order':job,'Qualifications, separated by commas':'Guard inspection reference'},'planning')
  assert.deepEqual((await h.api('planning',cookie.owner)).work.find(row=>row.id===job).qualifications,['Guard inspection reference'])
  await save('planning.tool',{'Tool name':'Guard alignment gauge','Serial or asset number':'synthetic-gasket-40','Calibration valid through':'2099-12-31'},'planning',form('planning.tool').filter({has:page.locator('input[name=name]:not([type=hidden])')}))
  assert.equal((await h.api('planning',cookie.owner)).tools.find(row=>row.name==='Guard alignment gauge').identifier,'synthetic-gasket-40')
  await open('/app/settings/resources','populated-resources')
  const retire=form('planning.retire').filter({has:page.locator('input[name=kind][value=tool]')}).last()
  await save('planning.retire',{'Retirement reason':'Gauge withdrawn after inspection'},'planning',retire)
  assert.ok((await h.api('planning',cookie.owner)).retired.some(row=>row.reason==='Gauge withdrawn after inspection'))
  await open('/app/settings/resources','retired-resource-history')

  await use('lead')
  await open('/app/teams','team-creation')
  await save('team.create',{'Team name':'Guard maintenance crew','Trade':'Mechanical'},'teams')
  const team=(await h.api('teams',cookie.lead)).find(row=>row.name==='Guard maintenance crew')
  assert.equal(team.trade,'Mechanical')
  await save('team.member',{'Add a person':technician},'teams',page.locator(`#team-${team.id}`).locator('form[action="/app/do/team.member"]').first())
  assert.deepEqual((await h.api('teams',cookie.lead)).find(row=>row.id===team.id).members.map(row=>row.id),[technician])
  await open(`/app/work/${job}`,'crew-assignment')
  await save('workorder.assign',{'Assign to':technician,'Team':team.id,'Shift':'Day','Handoff note':'Guard work belongs to the workshop crew'},work)
  assert.equal((await h.api(work,cookie.lead)).crew.team.id,team.id)
  const collaborator=(await h.api('me',cookie.lead)).id
  await save('workorder.collaborate',{'Add a collaborator':collaborator},work,form('workorder.collaborate').first())
  assert.deepEqual((await h.api(work,cookie.lead)).crew.collaborators.map(row=>row.id),[collaborator])
  await open(`/app/work/${job}`,'collaborator-removal')
  await save('workorder.collaborate',{'Remove a collaborator':collaborator},work,form('workorder.collaborate').last())
  assert.deepEqual((await h.api(work,cookie.lead)).crew.collaborators,[])
  await save('workorder.priority',{'Priority':'high','Reason':'Production guard needs prompt inspection'},work)
  assert.equal((await h.api(work,cookie.lead)).priority,'high')
  await save('workorder.reserve',{'Part':part,'Quantity':'1'},work,form('workorder.reserve').filter({has:page.locator('select[name=part]')}))
  assert.equal((await h.api(work,cookie.lead)).reservations.find(row=>row.part.id===part).state,'open')
  await open(`/app/work/${job}`,'reservation-release')
  await save('reservation.release',{'Reservation':(await h.api(work,cookie.lead)).reservations.find(row=>row.state==='open').id,'Reason':'Inspection uses the already issued fastener kit'},work)
  assert.equal((await h.api(work,cookie.lead)).reservations.find(row=>row.part.id===part).state,'released')
  await use('max')
  await open(`/app/work/${job}`,'crew-acknowledgment')
  await save('workorder.acknowledge',{},work)
  assert.ok((await h.api(work,cookie.max)).acknowledged_at)
  await save('comment.post',{'Comment':'Guard alignment inspected before the shift handoff'},work)
  assert.equal((await h.api(work,cookie.max)).comments.comments[0].body,'Guard alignment inspected before the shift handoff')
  await open(`/app/work/${job}`,'comment-correction')
  await save('comment.edit',{'Edit your comment':'Guard alignment inspected; isolate before further adjustment'},work,form('comment.edit').last())
  assert.equal((await h.api(work,cookie.max)).comments.comments[0].revisions.length,2)
  await open(`/app/work/${job}`,'corrected-comment-history')

  await use('lead')
  await open(`/app/assets/${asset}`,'asset-state-declaration')
  await save('asset.state',{'State':'degraded','Effective from':`${day}T07:00`,'Reason':'Guard resonance requires inspection'},record)
  assert.equal((await h.api(record,cookie.lead)).status,'degraded')
  await save('asset.sighting',{'What you found':'elsewhere','Where it was (if elsewhere)':'North maintenance bay','Note':'Moved for guard inspection'},record)
  assert.equal((await h.api(record,cookie.lead)).sightings[0].seen_location,'North maintenance bay')
  await save('meter.create',{'Meter name':'Guard inspection hours','Unit':'h'},record)
  const meter=(await h.api(record,cookie.lead)).meters[0].id
  await save('meter.window',{'Meter':meter,'Feed readings stale after (hours)':'36'},record)
  assert.equal((await h.api(record,cookie.lead)).meters[0].feed_window_hours,36)
  await open(`/app/assets/${asset}`,'populated-asset-history')

  await open(`/app/parts/${part}`,'vendor-price')
  await save('part.price',{'Price per unit (USD)':'4.25'},`parts/${part}`)
  assert.equal((await h.api(`parts/${part}`,cookie.lead)).price_cents,425)
  const alternate=(await h.api('part.create',cookie.lead,{number:'ACCESS-ALTERNATE',name:'Alternate guard fastener with extended manufacturer description',unit:'each'})).id
  await open(`/app/parts/${part}`,'substitute-approval')
  await save('part.substitute',{'Substitute part':alternate,'Reason':'Approved by maintenance for this guard'},`parts/${part}`)
  assert.equal((await h.api(`parts/${part}`,cookie.lead)).substitutes.length,1)
  await open('/app/parts','repair-kit-creation')
  const kit=form('kit.create')
  await kit.getByLabel('Part',{exact:true}).first().selectOption(part)
  await kit.getByLabel('Quantity',{exact:true}).first().fill('1')
  await save('kit.create',{'Kit name':'Guard inspection fastener kit'},'kits',kit)
  assert.deepEqual((await h.api('kits',cookie.lead)).kits.find(row=>row.name==='Guard inspection fastener kit').lines.map(row=>[row.id,row.quantity]),[[part,'1']])
  await open('/app/parts','populated-repair-kits')
  await open(`/app/assets/${asset}`,'lifecycle-entry')
  await save('asset.lifecycle',{'Purchased on':day,'Purchase cost (USD)':'1500','Supplier':'Synthetic workshop equipment','Commissioned on':day,'Replacement value (USD)':'2400','Replacement value basis':'Supplier quotation entered by the maintenance lead'},record)
  assert.equal((await h.api(record,cookie.lead)).lifecycle.facts.purchase_cents,150000)
  await save('asset.agreement',{'Provider':'Synthetic workshop service company','Reference':'synthetic-gasket-41','Starts':day,'Ends':'2099-12-31','Annual cost (USD)':'300','Scope':'Guard inspection and mechanical alignment'},record)
  assert.equal((await h.api(record,cookie.lead)).lifecycle.agreements[0].annual_cents,30000)
  await form('bom.revise').getByLabel('Part',{exact:true}).first().selectOption(part)
  await form('bom.revise').getByLabel('Needed',{exact:true}).first().fill('1')
  await save('bom.revise',{},record,form('bom.revise'))
  assert.equal((await h.api(record,cookie.lead)).bom.revision,1)
  await open(`/app/assets/${asset}`,'retained-lifecycle-and-bom')

  await open('/app/templates','work-field-definition')
  await save('workfield.save',{'Field':'Guard inspection reference','Kind':'text'},'work-fields')
  const workField=(await h.api('work-fields',cookie.lead)).fields.find(row=>row.label==='Guard inspection reference')
  assert.equal(workField.kind,'text')
  await form('workstatus.save').getByLabel('Leads',{exact:true}).check()
  await save('workstatus.save',{'Status':'Waiting for guard access'},'work-fields')
  const waiting=(await h.api('work-fields',cookie.lead)).statuses.find(row=>row.label==='Waiting for guard access')
  assert.ok(waiting.id)
  await save('template.save',{'Name':'Guard adjustment template','Work title':'Adjust the guard using the approved procedure','Instructions':'Isolate before adjusting alignment','Estimated hours':'1'},'templates',page.locator('#new').locator('form'))
  const template=(await h.api('templates',cookie.lead)).find(row=>row.name==='Guard adjustment template')
  assert.equal(template.estimate_minutes,60)
  await open(`/app/work/${job}`,'custom-work-values')
  await save('workorder.field',{'Guard inspection reference':'synthetic-gasket-42'},work,form('workorder.field').filter({has:page.locator(`[name=field][value="${workField.id}"]`)}))
  assert.equal((await h.api(work,cookie.lead)).fields.find(row=>row.id===workField.id).value,'synthetic-gasket-42')
  await save('workorder.waiting',{'Waiting status':waiting.id},work)
  assert.equal((await h.api(work,cookie.lead)).waiting_status,waiting.id)
  await open(`/app/work/${job}`,'waiting-work-and-field-history')
  await open('/app/templates','template-retirement')
  await save('template.retire',{},'templates',form('template.retire').filter({has:page.locator(`[name=template][value="${template.id}"]`)}))
  assert.ok((await h.api('templates',cookie.lead)).find(row=>row.id===template.id).retired_at)
  await save('workfield.retire',{'Field':workField.id},'work-fields')
  assert.ok((await h.api('work-fields',cookie.lead)).fields.find(row=>row.id===workField.id).retired_at)
  await open('/app/templates','retired-template-and-field')

  await open('/app/codes','failure-code-definition')
  const codeForm=action=>page.locator('#failure_mode').locator(`form[action="/app/do/${action}"]`)
  await save('code.set',{'Key':'guard_resonance','Label':'Guard resonance after a fastener inspection','Import names':'Guard vibration'},'codes',codeForm('code.set'))
  assert.equal((await h.api('codes',cookie.lead)).find(row=>row.key==='guard_resonance').label,'Guard resonance after a fastener inspection')
  await h.api('code.set',cookie.lead,{kind:'failure_mode',key:'guard_alignment',label:'Guard alignment'})
  await open('/app/codes','failure-code-order')
  await save('code.move',{'Code':'guard_resonance','Move to position':'1'},'codes',codeForm('code.move'))
  assert.equal((await h.api('codes',cookie.lead)).filter(row=>row.kind==='failure_mode').sort((a,b)=>a.position-b.position)[0].key,'guard_resonance')
  await save('code.retire',{'Code':'guard_resonance','Reason':'Use the revised mechanical fault classification'},'codes',codeForm('code.retire'))
  assert.equal((await h.api('codes',cookie.lead)).find(row=>row.key==='guard_resonance').retired,true)
  await open('/app/codes','retired-failure-code')
  await open('/app/availability','production-hours-entry')
  await form('production.hours.add').getByLabel('Monday',{exact:true}).check()
  await save('production.hours.add',{'Starts':'07:00','Ends':'15:00'},'availability')
  const hours=(await h.api('availability',cookie.lead)).production.hours.find(row=>row.starts==='07:00'&&row.ends==='15:00')
  assert.equal(hours.weekday,1)
  await save('production.hours.remove',{'Remove a window':hours.id},'availability')
  assert.equal((await h.api('availability',cookie.lead)).production.hours.some(row=>row.id===hours.id),false)

  await open('/app/notices','chase-policy-entry')
  await save('chase.rule',{'Remind before due (days)':'2','Response expected within (days)':'2','Escalate to leads after (days overdue)':'3','Escalate to supervisors after (days overdue)':'5'},'chase-rule')
  assert.equal((await h.api('chase-rule',cookie.lead)).remind_before_days,2)
  await open(`/app/work/${job}`,'work-blocker-entry')
  await save('blocker.raise',{'Blocked by':'access','Next action':'Request access to the guard platform','Promised by':day},work)
  assert.equal((await h.api(work,cookie.lead)).chase.blockers[0].kind,'access')
  await open(`/app/work/${job}`,'blocker-resolution')
  await save('blocker.resolve',{'What cleared the access blocker':'Production released the platform'},work,form('blocker.resolve').last())
  assert.equal((await h.api(work,cookie.lead)).chase.blockers[0].resolution,'Production released the platform')
  await use('max')
  await open(`/app/work/${job}`,'assignee-response')
  await save('workorder.respond',{},work,form('workorder.respond').filter({has:page.locator('[name=response][value=on_it]')}))
  assert.equal((await h.api(work,cookie.max)).chase.responses.at(-1).response,'on_it')
  await open(`/app/work/${job}`,'recorded-response')
  await use('lead')
  await open(`/app/assets/${asset}`,'document-original')
  const original={name:'synthetic-gasket-43.png',mimeType:['image','png'].join('/'),buffer:png}
  await save('document.add',{'Title':'Guard alignment instructions with retained original drawings','File':original,'Source (publisher and reference)':'Owner-entered synthetic workshop instructions'},record)
  const document=(await h.api(record,cookie.lead)).documents.documents.find(row=>row.title==='Guard alignment instructions with retained original drawings')
  assert.equal(document.revisions[0].filename,original.name)
  const revise=form('document.revise').filter({has:page.locator(`[name=document][value="${document.id}"]`)})
  await save('document.revise',{'File':{...original,name:'synthetic-gasket-44.png'},'What changed':'Add the guard fastener inspection'},record,revise)
  assert.deepEqual((await h.api(record,cookie.lead)).documents.documents.find(row=>row.id===document.id).revisions.map(row=>row.filename),['synthetic-gasket-44.png',original.name])
  await save('document.expiry',{'Expires on':'2099-12-31','Owner to remind':technician,'Remind days ahead':'14'},record,form('document.expiry').filter({has:page.locator(`[name=document][value="${document.id}"]`)}))
  assert.equal((await h.api(record,cookie.lead)).documents.documents.find(row=>row.id===document.id).remind_days,14)
  await save('asset.contact',{'Name':'Synthetic workshop service desk','Company':'Synthetic mechanical services','Phone':'+1 216 555 0143','Email':'synthetic-gasket-service@example.test'},record)
  assert.equal((await h.api(record,cookie.lead)).documents.contacts[0].name,'Synthetic workshop service desk')
  await open(`/app/work/${job}`,'document-link')
  await save('document.link',{'Document':document.id},work)
  assert.deepEqual((await h.api(work,cookie.lead)).documents.map(row=>[row.title,row.revision]),[[document.title,2]])
  await save('work.cost',{'Category':'tools','Amount (USD)':'35.50','Note':'Guard alignment tool rental'},work)
  assert.equal((await h.api(work,cookie.lead)).costs.totalCents,3550)
  await open(`/app/work/${job}`,'linked-documents-and-cost')
  await open('/app/settings/fields','custom-asset-field')
  await save('customfield.save',{'Field name':'Guard inspection register note','Record type':'asset','Type':'text','Scope':'organization'},'custom-fields',page.locator('#define-field').locator('form'))
  const custom=(await h.api('custom-fields',cookie.lead)).find(row=>row.name==='Guard inspection register note')
  assert.equal(custom.type,'text')
  await open(`/app/assets/${asset}`,'custom-asset-value')
  await save('customvalue.set',{'Guard inspection register note':'Inspect the north guard platform'},record)
  assert.equal((await h.api(record,cookie.lead)).customFields.find(row=>row.id===custom.id).value,'Inspect the north guard platform')
  await open('/app/settings/fields','archive-custom-field')
  await save('customfield.retire',{},'custom-fields',form('customfield.retire').filter({has:page.locator(`[name=id][value="${custom.id}"]`)}))
  assert.equal(Boolean((await h.api('custom-fields',cookie.lead)).find(row=>row.id===custom.id).retired),true)
  await open(`/app/assets/${asset}`,'archived-custom-value')
  await open(`/app/parts/${part}`,'part-category')
  await save('part.category',{'Category':'Guard fasteners'},`parts/${part}`)
  assert.equal((await h.api(`parts/${part}`,cookie.lead)).category,'Guard fasteners')
  await open('/app/schedules','closed-day-entry')
  await save('closure.add',{'Name':'Guard workshop shutdown','From':day,'To (inclusive)':day},'closures')
  const closure=(await h.api('closures',cookie.lead)).find(row=>row.label==='Guard workshop shutdown')
  assert.equal(closure.starts_on,day)
  await save('closure.remove',{},'closures',form('closure.remove').filter({has:page.locator(`[name=closure][value="${closure.id}"]`)}))
  assert.equal((await h.api('closures',cookie.lead)).some(row=>row.id===closure.id),false)
  await open('/app/bad-actors','production-loss-rate')
  await save('loss.rate',{'Entry':asset,'USD per production hour':'120.00','Basis':'Documented synthetic production contribution'},'bad-actors')
  assert.match(await page.getByRole('main').innerText(),/120\.00 per production hour/)
  const parent=(await h.api('asset.create',cookie.lead,{tag:'ACCESS-PARENT',name:'Workshop guard inspection line',location:'West workshop',level:'line'})).id
  await open(`/app/assets/${asset}`,'move-maintenance-hierarchy')
  await save('asset.move',{'Move under':parent},record)
  assert.equal((await h.api(record,cookie.lead)).hierarchy.parent.id,parent)
  const retired=(await h.api('asset.create',cookie.lead,{tag:'ACCESS-RETIRED',name:'Retired workshop guard fixture with retained maintenance identity',location:'West workshop'})).id
  await open(`/app/assets/${retired}`,'asset-retirement')
  await save('asset.retire',{'Reason to retire':'Replaced by the approved guard fixture'},`assets/${retired}`)
  assert.equal((await h.api(`assets/${retired}`,cookie.lead)).status,'retired')
  await open(`/app/assets/${retired}`,'retired-asset-history')
  await use('owner')
  await open('/app/site','technician-create-work-setting')
  const allowed=(await h.api('site',cookie.owner)).technician_create_work
  await save('site.technicianWork',{},'site')
  assert.equal(Boolean((await h.api('site',cookie.owner)).technician_create_work),!Boolean(allowed))
  await open('/app/site','changed-technician-create-work-setting')
  await proof('conditional-saves-complete')
}
