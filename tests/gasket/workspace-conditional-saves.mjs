  await save('blocker.resolve',{'What cleared the access blocker':'Production released the platform'},work,form('blocker.resolve').last())
  assert.equal((await h.api(work,cookie.lead)).chase.blockers[0].resolution,'Production released the platform')
  await use('max')
  await open(`/app/work/${job}`,'assignee-response')
  await save('workorder.respond',{},work,form('workorder.respond').filter({has:page.locator('[name=response][value=on_it]')}))
  assert.equal((await h.api(work,cookie.max)).chase.responses.at(-1).response,'on_it')
  await open(`/app/work/${job}`,'recorded-response')
  await use('lead')
  await open(`/app/assets/${asset}`,'document-original')
